// Prints supabase/seed.sql from the demo seed data. Run with: npm run seed:sql
import { randomUUID } from 'node:crypto';
import { seedEpisodes } from '../src/data/seed';

const q = (s: string | null | undefined) => (s == null || s === '' ? (s === '' ? "''" : 'null') : `'${s.replace(/'/g, "''")}'`);
const arr = (a: boolean[]) => `array[${a.join(', ')}]`;
let tick = 0;
// Distinct created_at values keep clips, posts and handoffs in their seeded order.
const ts = () => `timestamptz '2026-09-01 00:00:00+00' + interval '${tick++} seconds'`;

const out: string[] = ['-- Sample data for Episode Tracker. Generated by scripts/gen-seed-sql.ts.', 'begin;'];
for (const e of seedEpisodes()) {
  const eid = randomUUID();
  out.push(
    `insert into public.episodes (id, num, title, stage, record_date, due_date, entered_date, blocked, drive_url, pkg) values ('${eid}', ${e.num}, ${q(e.title)}, ${e.stage}, '${e.record}', '${e.due}', '${e.entered}', ${q(e.blocked)}, ${q(e.drive)}, ${arr(e.pkg)});`,
  );
  for (const h of e.handoffs)
    out.push(`insert into public.handoffs (episode_id, from_stage, to_stage, date, note, created_at) values ('${eid}', ${h.fs}, ${h.ts}, '${h.date}', ${q(h.note)}, ${ts()});`);
  for (const c of e.clips) {
    const cid = randomUUID();
    out.push(`insert into public.clips (id, episode_id, name, length, caption, created_at) values ('${cid}', '${eid}', ${q(c.name)}, ${q(c.len)}, ${q(c.caption)}, ${ts()});`);
    for (const p of c.posts)
      out.push(
        `insert into public.posts (clip_id, platform, date, time, status, url, checks, verified, verified_date, created_at) values ('${cid}', '${p.plat}', '${p.date}', '${p.time}', '${p.status}', ${q(p.url)}, ${arr(p.checks)}, ${p.verified}, ${p.vDate ? `'${p.vDate}'` : 'null'}, ${ts()});`,
      );
  }
}
out.push('commit;');
console.log(out.join('\n'));
